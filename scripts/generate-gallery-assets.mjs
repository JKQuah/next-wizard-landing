/**
 * Regenerates src/content/gallery.ts from the AVIF files in src/assets.
 *
 *   pnpm gallery:assets
 *
 * Run it after adding, renaming or removing a poster. For every file it writes
 * a static import (so Next knows the exact size and serves a content-hashed
 * URL), the file's real width and height, and a ~100 byte blurred preview that
 * the gallery shows while the full image is still downloading. Next reports
 * every AVIF as 100x100 with a blank 1px blur, which is why those are read and
 * made here instead.
 *
 * Layout it expects:
 *   src/assets/gallery/<id>.avif
 *   src/assets/star-student/<month-id>/<id>.avif
 * where <id> and <month-id> match the ids in the en.json / zh.json dictionaries.
 */
import { readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

// sharp is a dependency of Next.js itself, so resolve it from there.
const require = createRequire(import.meta.url);
const sharp = require(
  require.resolve("sharp", { paths: [require.resolve("next/package.json")] }),
);

const ASSETS = "src/assets";
const OUT = "src/content/gallery.ts";
const PREVIEW_WIDTH = 12;

const avifs = (dir) =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".avif"))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));

const identifier = (text) =>
  text
    .replace(/[^a-zA-Z0-9]+(\w)/g, (_, c) => c.toUpperCase())
    .replace(/^(\d)/, "_$1");

/** The call that goes into the generated file: real size plus blur preview. */
async function entry(name, file) {
  const { width, height } = await sharp(file).metadata();
  const data = await sharp(file)
    .resize({ width: PREVIEW_WIDTH })
    .webp({ quality: 40 })
    .toBuffer();
  const blur = `data:image/webp;base64,${data.toString("base64")}`;
  return `image(${name}, ${width}, ${height}, "${blur}")`;
}

const imports = [];
const galleryRows = [];
const starBlocks = [];

for (const file of avifs(`${ASSETS}/gallery`)) {
  const id = file.replace(".avif", "");
  const name = identifier(`gallery-${id}`);
  imports.push(`import ${name} from "@/assets/gallery/${file}";`);
  galleryRows.push(
    `  "${id}": ${await entry(name, `${ASSETS}/gallery/${file}`)},`,
  );
}

const months = readdirSync(`${ASSETS}/star-student`, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .reverse();

for (const month of months) {
  const rows = [];
  for (const file of avifs(`${ASSETS}/star-student/${month}`)) {
    const id = file.replace(".avif", "");
    const name = identifier(`star-${month}-${id}`);
    imports.push(`import ${name} from "@/assets/star-student/${month}/${file}";`);
    rows.push(
      `    "${id}": ${await entry(name, `${ASSETS}/star-student/${month}/${file}`)},`,
    );
  }
  starBlocks.push(`  "${month}": {\n${rows.join("\n")}\n  },`);
}

writeFileSync(
  OUT,
  `/**
 * Every gallery image. GENERATED by scripts/generate-gallery-assets.mjs: run
 * \`pnpm gallery:assets\` after adding or removing a file in src/assets rather
 * than editing this by hand.
 *
 * Each image is a static import, so Next serves it from a content-hashed,
 * cache-forever URL. The real size and a tiny blurred preview (shown until the
 * full image has loaded) are filled in here because Next can't read them from
 * AVIF. The files are AVIF, at most 1080px.
 */
import type { StaticImageData } from "next/image";

${imports.join("\n")}

const image = (
  data: StaticImageData,
  width: number,
  height: number,
  blurDataURL: string,
): StaticImageData => ({ ...data, width, height, blurDataURL });

/** Keyed by the item id used in the dictionaries. */
export const galleryImages: Record<string, StaticImageData> = {
${galleryRows.join("\n")}
};

/** Keyed by month id, then by the item id used in the dictionaries. */
export const starStudentImages: Record<
  string,
  Record<string, StaticImageData>
> = {
${starBlocks.join("\n")}
};
`,
);

console.log(
  `Wrote ${OUT}: ${galleryRows.length} gallery images, ${months.length} star student months.`,
);
