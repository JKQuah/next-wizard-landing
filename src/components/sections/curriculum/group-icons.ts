export type GroupIconName = keyof typeof groupIcons;

/**
 * Icon for a skill group, matched on the group's title. The syllabus has the
 * same groups in English and Chinese, so every rule lists both words. Order
 * matters: a more specific rule has to come before the general one it contains
 * ("Operation of Decimals" before "Decimals", "Area of Triangle" before "Area").
 */
const rules: [RegExp, GroupIconName][] = [
  [/addition and subtraction|加法与减法/i, "Diff"],
  [/addition|加法/i, "Plus"],
  [/subtraction|减法/i, "Minus"],
  [/multiplication|乘法/i, "X"],
  [/division|除法/i, "Divide"],
  [/ordinal|序数/i, "ListOrdered"],
  [/operation of decimals|小数的运算/i, "Calculator"],
  [/decimal|小数/i, "CircleDot"],
  [/percent|百分数/i, "Percent"],
  [/fraction|分数/i, "ChartPie"],
  [/factors|因数|倍数/i, "Grid3x3"],
  [/algebra|代数/i, "Variable"],
  [/ratio|^比$/i, "Scale"],
  [/\brate\b|^率$/i, "TrendingUp"],
  [/speed|速度/i, "Gauge"],
  [/average|平均/i, "Sigma"],
  [/picture graph|象形|data analysis|数据分析/i, "ChartColumn"],
  [/2d\/3d|平面图形与立体图形/i, "Shapes"],
  [/3d|立体图形/i, "Box"],
  [/2d|平面图形/i, "Square"],
  [/shapes|^图形$/i, "Shapes"],
  [/area of triangle|三角形面积/i, "Triangle"],
  [/area|perimeter|面积|周长/i, "SquareDashed"],
  [/circle|^圆$/i, "Circle"],
  [/angle|^角$/i, "Angle"],
  [/lines?\b|^线$/i, "Slash"],
  [/pattern|规律/i, "Repeat"],
  [/length|长度/i, "Ruler"],
  [/mass|质量/i, "Weight"],
  [/volume|体积|容量/i, "Beaker"],
  [/time|时间/i, "Clock"],
  [/money|钱币/i, "Coins"],
  [/numbers?|whole|整数|的数/i, "Hash"],
];

export function groupIconName(title: string): GroupIconName {
  return rules.find(([pattern]) => pattern.test(title))?.[1] ?? "Sparkles";
}
